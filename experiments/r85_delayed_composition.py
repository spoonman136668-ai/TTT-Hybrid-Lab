def git_blob(raw: bytes) -> str:
    raw = raw.replace(b"\r\n", b"\n")
    if b"\r" in raw:
        raise RuntimeError("R85_UNEXPECTED_CARRIAGE_RETURN")
    return hashlib.sha1(b"blob " + str(len(raw)).encode() + b"\0" + raw).hexdigest()


def frozen() -> dict:
    if git_blob(FREEZE.read_bytes()) != FREEZE_BLOB:
        raise RuntimeError("R85_FROZEN_PROTOCOL_BLOB_DRIFT")
    if git_blob(R84_FREEZE.read_bytes()) != R84_FREEZE_BLOB:
        raise RuntimeError("R85_R84_SOURCE_CUSTODY_DRIFT")
    f = json.loads(FREEZE.read_text(encoding="utf-8"))
    p, s, g = f["parent"], f["source"], f["gates"]
    if (f["schema"] != SCHEMA
        or f["stage"] != "IMMUTABLE_R85_PROSPECTIVE_FREEZE_BEFORE_IMPLEMENTATION_TESTS_OR_SOURCE_FIRST_USE"
        or p["R84_candidate_SHA"] != PARENT
        or p["R84_original_science"] != "DEV_LEARNED_INTERVENTION_NO_GO_BOTH_SEEDS"
        or p["R84_freeze_blob"] != R84_FREEZE_BLOB
        or s["independent_salts"] != {
            "CALIBRATION": SALT, "QUALIFICATION_SEALED": 25270211,
            "DEV_SEALED": 25270311, "OOD_SEALED": 25270411}
        or s["seeds"] != list(SEEDS)
        or s["calibration_worlds_per_seed"] != N
        or s["episode_length"] != LENGTH or s["early_pivot"] != EARLY
        or s["cold_pivot"] != COLD
        or s["law_phases"]["A_probe_times"] != list(A_PROBES)
        or s["law_phases"]["B_probe_times"] != list(B_PROBES)
        or s["access_now"] != "CALIBRATION ONLY; QUALIFICATION_SEALED, DEV_SEALED, OOD_SEALED are never generated by R85"
        or g["both_seeds_required"] is not True
        or g["paired_world_bootstrap_resamples"] != 2000
        or g["A_parity_sign_accuracy_min"] != .9
        or g["public_minus_best_fixed_reward_min"] != 1.75
        or g["public_minus_shuffled_A_reward_min"] != 1.75
        or g["public_minus_last_A_cue_reward_min"] != 1.75
        or g["public_minus_recent_B_reward_cold_min"] != 1.5
        or g["public_oracle_regret_max"] != .6
        or g["paired_bootstrap_lower95_public_minus_best_fixed_min"] != 1.0
        or any(f["authority"].values())):
        raise PermissionError("R85_SOURCE_OR_THRESHOLD_CONTRACT_DRIFT")
    return f


def _make_synthetic_world(index: int, rng: np.random.Generator) -> dict:
    """Pure physics constructor. Unit tests pass independent TEST RNG only."""
    if not isinstance(index, int) or not 0 <= index < N:
        raise ValueError("R85_WORLD_INDEX_OUT_OF_RANGE")
    pivot = EARLY if index % 2 == 0 else COLD
    # Exact within-stratum balance, while public time/pivot does not reveal sign.
    law = 1 if (index // 2) % 2 == 0 else -1
    a = np.empty(4, dtype=np.int64)
    a[:3] = rng.choice([-1, 1], size=3)
    a[3] = int(law * np.prod(a[:3]))
    b = rng.choice([-1, 1], size=4).astype(np.int64)
    actions = rng.choice([2, 3], size=LENGTH).astype(np.int64)
    a_perm = rng.permutation(4)
    b_perm = rng.permutation(4)
    probe = {}
    for i, t in enumerate(A_PROBES):
        probe[t] = ("A", int(a_perm[i]), 1)
        actions[t] = PROBE
    for i, t in enumerate(B_PROBES):
        probe[t] = ("B", int(b_perm[i]), -1)
        actions[t] = PROBE
    # Pre-pivot B probes on early worlds would be future-only and not observed.
    innovations = rng.standard_normal((LENGTH, 4))
    return {
        "pivot": pivot, "law_a": int(np.prod(a)),
        "law_b": int(np.prod(b)), "factors_a": a, "factors_b": b,
        "probe": probe, "actions": actions, "innovations": innovations,
        "a_probe_permutation": a_perm, "b_probe_permutation": b_perm
    }


def _world(panel: str, seed: int, index: int, *, custody_sha: str | None = None) -> dict:
    frozen()
    if panel != "CALIBRATION":
        raise PermissionError("R85_SEALED_OR_SPENT_PANEL_ACCESS_DENIED")
    if seed not in SEEDS or not isinstance(index, int) or not 0 <= index < N:
        raise PermissionError("R85_UNFROZEN_SEED_OR_WORLD_INDEX")
    if (not custody_sha or custody_sha != os.getenv("EXPECTED_CANDIDATE_SHA")
        or os.getenv("GITHUB_ACTIONS") != "true"
        or os.getenv("GITHUB_HEAD_REF") != BRANCH):
        raise PermissionError("R85_CALIBRATION_SOURCE_NOT_ADMITTED")
    rng = np.random.default_rng(np.random.SeedSequence([SALT, seed, index]))
    return _make_synthetic_world(index, rng)


def _rollout(world: dict, chosen: int):
    if chosen not in (CALIBRATE, EXPLOIT_POS):
        raise ValueError("R85_UNREGISTERED_INTERVENTION")
    p = world["pivot"]
    x = np.zeros((p + 1, 13), dtype=np.float32)
    prior_action = None
    prior_observed = np.zeros(4, dtype=np.float32)
    state = 0
    reward = 0.0
    for t in range(p + 9):
        action = chosen if t == p else (
            EXPLOIT_POS if t > p else int(world["actions"][t]))
        if t <= p:
            x[t, action] = 1.0
            if prior_action is not None:
                x[t, 4 + prior_action] = 1.0
            x[t, 8:12] = prior_observed
            x[t, 12] = t / (LENGTH - 1)
        eps = world["innovations"][t]
        if t < p:
            if t in world["probe"]:
                phase, role, marker = world["probe"][t]
                factor = world["factors_a" if phase == "A" else "factors_b"][role]
                observed = np.array([
                    -.1 + .01 * eps[0], (role + 1) / 4,
                    float(factor) + .4 * eps[2], marker
                ], dtype=np.float32)
            else:
                # Neither rewards nor ambient observations reveal factor/law.
                observed = np.array([
                    .01 * eps[0], .01 * eps[1], .01 * eps[2], 0
                ], dtype=np.float32)
        elif t == p and action == CALIBRATE:
            # The current A phase has returned by t160 in cold worlds.
            state = world["law_a"]
            observed = np.array([-.5, eps[1], eps[2], eps[3]], np.float32)
        else:
            if action != EXPLOIT_POS:
                raise RuntimeError("R85_POST_PIVOT_NOT_COMMON_EXPLOIT")
            law = world["law_a"]
            amp, penalty = (1.0, 0.0) if state == law else (.2, -.1)
            observed = np.array([
                amp * law + penalty + .1 * eps[0],
                eps[1], eps[2], eps[3]
            ], dtype=np.float32)
        if t >= p:
            reward += float(observed[0])
        prior_action = action
        prior_observed = observed
    return x, reward


def _public_probes(prefix: np.ndarray, marker: int):
    # PROBE actual at t is available ONLY in selected observation at t+1.
    rows = prefix[(prefix[:, 5] == 1) & (prefix[:, 11] == marker)]
    seen = set()
    result = []
    for row in rows:
        role = int(round(float(row[9]) * 4)) - 1
        if role not in (0, 1, 2, 3) or role in seen:
            raise RuntimeError("R85_MISSING_OR_DUPLICATED_PUBLIC_ROLE")
        seen.add(role)
        result.append((role, float(row[10])))
    if len(result) != 4 or seen != {0, 1, 2, 3}:
        raise RuntimeError("R85_PUBLIC_CAUSAL_PROBE_TRACE_INCOMPLETE")
    return result


def _policy(prefix: np.ndarray, mode: str = "A_PARITY") -> int:
    a = _public_probes(prefix, 1)
    if mode == "A_PARITY":
        sign = int(np.prod([1 if v > 0 else -1 for _, v in a]))
    elif mode == "LAST_A":
        sign = 1 if a[-1][1] > 0 else -1
    elif mode == "RECENT_B":
        b_rows = prefix[(prefix[:, 5] == 1) & (prefix[:, 11] == -1)]
        if len(b_rows):
            b = _public_probes(prefix, -1)
            sign = int(np.prod([1 if v > 0 else -1 for _, v in b]))
        else:
            sign = 1 if a[-1][1] > 0 else -1
    else:
        raise ValueError("R85_UNREGISTERED_PUBLIC_RULE")
    return CALIBRATE if sign > 0 else EXPLOIT_POS


def _paired_public(world: dict):
    x0, r0 = _rollout(world, CALIBRATE)
    x2, r2 = _rollout(world, EXPLOIT_POS)
    p = world["pivot"]
    if (not np.array_equal(x0[:p], x2[:p])
        or not np.array_equal(x0[p, 4:], x2[p, 4:])
        or not (x0[p, 0] == x2[p, 2] == 1.0)
        or np.any(x0[p, 1:4]) or np.any(x2[p, :2])
        or x2[p, 3] != 0):
        raise RuntimeError("R85_CAUSAL_PREFIX_OR_ACTION_LEAK")
    return x0, x2, r0, r2


def _bootstrap_lower(delta: np.ndarray, seed: int) -> float:
    if delta.shape != (N,):
        raise RuntimeError("R85_INVALID_BOOTSTRAP_SHAPE")
    rng = np.random.default_rng(np.random.SeedSequence([25270555, seed]))
    indices = rng.integers(0, N, size=(2000, N))
    return float(np.quantile(delta[indices].mean(axis=1), .025))


def _diagnostic(seed: int, *, custody_sha: str) -> dict:
    if custody_sha != _admit():
        raise PermissionError("R85_DIAGNOSTIC_NOT_ADMITTED")
    if seed not in SEEDS:
        raise PermissionError("R85_UNREGISTERED_FIRST_USE_SEED")
    # Invocable from ORIGINAL admitted CI only. CALIBRATION is now consumed.
    worlds = [_world("CALIBRATION", seed, i, custody_sha=custody_sha) for i in range(N)]
    paired = [_paired_public(w) for w in worlds]
    x = [q[0] for q in paired]
    r0 = np.array([q[2] for q in paired], np.float64)
    r2 = np.array([q[3] for q in paired], np.float64)
    truth = np.array([w["law_a"] for w in worlds], np.int64)
    pivot = np.array([w["pivot"] for w in worlds], np.int64)
    act = np.array([_policy(p) for p in x], np.int64)
    last = np.array([_policy(p, "LAST_A") for p in x], np.int64)
    recent = np.array([_policy(p, "RECENT_B") for p in x], np.int64)
    # A whole four-probe observation trace is shuffled within each pivot
    # stratum; the target world's physical outcomes remain unchanged.
    shuffle = np.arange(N)
    shuffle_rng = np.random.default_rng(np.random.SeedSequence([25270555, seed, 1]))
    for p in (EARLY, COLD):
        ix = np.flatnonzero(pivot == p)
        shuffle[ix] = shuffle_rng.permutation(ix)
    wrong = []
    for i, original in enumerate(x):
        altered = original.copy()
        donor = x[int(shuffle[i])]
        for t in A_PROBES:
            altered[t + 1, 8:12] = donor[t + 1, 8:12]
        wrong.append(_policy(altered))
    wrong = np.array(wrong, np.int64)
    realized = lambda choices: np.where(choices == CALIBRATE, r0, r2)
    public = realized(act)
    last_return = realized(last)
    recent_return = realized(recent)
    shuffled_return = realized(wrong)
    fixed_choice = CALIBRATE if r0.mean() >= r2.mean() else EXPLOIT_POS
    best_fixed = realized(np.full(N, fixed_choice, dtype=np.int64))
    oracle = np.maximum(r0, r2)
    groups = {}
    for name, p in (("early", EARLY), ("cold", COLD)):
        ix = pivot == p
        fixed_mean = max(float(r0[ix].mean()), float(r2[ix].mean()))
        groups[name] = {
            "n": int(ix.sum()),
            "A_positive": int(np.sum(truth[ix] == 1)),
            "mean_public_reward": float(public[ix].mean()),
            "best_fixed_reward": fixed_mean,
            "public_minus_best_fixed": float(public[ix].mean() - fixed_mean)}
    lower = _bootstrap_lower(public - best_fixed, seed)
    accuracy = float(np.mean(np.where(act == CALIBRATE, 1, -1) == truth))
    comp = {
        "A_parity_sign_accuracy": accuracy,
        "public_reward": float(public.mean()),
        "best_fixed_reward": float(best_fixed.mean()),
        "shuffled_A_reward": float(shuffled_return.mean()),
        "last_A_cue_reward": float(last_return.mean()),
        "recent_B_cold_reward": float(recent_return[pivot == COLD].mean()),
        "public_minus_best_fixed": float(public.mean() - best_fixed.mean()),
        "public_minus_shuffled_A": float(public.mean() - shuffled_return.mean()),
        "public_minus_last_A_cue": float(public.mean() - last_return.mean()),
        "cold_public_minus_recent_B": float(public[pivot == COLD].mean() - recent_return[pivot == COLD].mean()),
        "public_oracle_regret": float((oracle - public).mean()),
        "paired_bootstrap_lower95_public_minus_best_fixed": lower}
    t = frozen()["gates"]
    checks = {
        "A_parity_sign_accuracy": accuracy >= t["A_parity_sign_accuracy_min"],
        "public_vs_best_fixed": comp["public_minus_best_fixed"] >= t["public_minus_best_fixed_reward_min"],
        "public_vs_shuffled_A": comp["public_minus_shuffled_A"] >= t["public_minus_shuffled_A_reward_min"],
        "public_vs_last_A": comp["public_minus_last_A_cue"] >= t["public_minus_last_A_cue_reward_min"],
        "cold_public_vs_recent_B": comp["cold_public_minus_recent_B"] >= t["public_minus_recent_B_reward_cold_min"],
        "early_vs_fixed": groups["early"]["public_minus_best_fixed"] >= t["early_public_minus_best_fixed_min"],
        "cold_vs_fixed": groups["cold"]["public_minus_best_fixed"] >= t["cold_public_minus_best_fixed_min"],
        "oracle_regret": comp["public_oracle_regret"] <= t["public_oracle_regret_max"],
        "paired_bootstrap": lower >= t["paired_bootstrap_lower95_public_minus_best_fixed_min"],
        "balanced_A_laws_each_group": all(
            g["n"] == 256 and g["A_positive"] == 128 for g in groups.values())}
    return {"seed": seed, "CALIBRATION_worlds": N, "comparison": comp,
            "groups": groups, "frozen_checks": {k: bool(v) for k, v in checks.items()},
            "pass": all(checks.values())}


def _admit() -> str:
    frozen()
    if (os.getenv("GITHUB_ACTIONS") != "true"
        or os.getenv("GITHUB_EVENT_NAME") != "pull_request"
        or os.getenv("GITHUB_HEAD_REF") != BRANCH
        or os.getenv("GITHUB_REPOSITORY") != "spoonman136668-ai/TTT-Hybrid-Lab"
        or os.getenv("RUNNER_OS") != "Linux"
        or os.getenv("RUNNER_ENVIRONMENT") != "github-hosted"
        or os.getenv("GITHUB_RUN_ATTEMPT") != "1"
        or "/merge" not in os.getenv("GITHUB_REF", "")):
        raise PermissionError("R85_NOT_ORIGINAL_QUALIFIED_HOSTED_PR_FIRST_ATTEMPT")
    expected = os.getenv("EXPECTED_CANDIDATE_SHA", "")
    head = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT,
        capture_output=True, text=True, check=False, timeout=10)
    clean = subprocess.run(["git", "diff", "--quiet", "HEAD", "--"], cwd=ROOT,
        capture_output=True, text=True, check=False, timeout=10)
    if (len(expected) != 40 or head.returncode != 0
        or head.stdout.strip() != expected or clean.returncode != 0):
        raise PermissionError("R85_EXACT_SHA_OR_CLEAN_SOURCE_MISMATCH")
    return expected


def original_ci() -> dict:
    sha = _admit()  # Must fail closed before accessing any CALIBRATION world.
    path = ROOT / "local_runs/r85_delayed_composition_calibration.json"
    if path.exists():
        raise FileExistsError("R85_UNCERTAIN_OR_DUPLICATE_CALIBRATION_REFUSED")
    begin = time.perf_counter()
    results = [_diagnostic(seed, custody_sha=sha) for seed in SEEDS]
    pass_all = all(item["pass"] for item in results)
    g = frozen()["gates"]
    receipt = {
        "schema": SCHEMA, "candidate_SHA": sha,
        "freeze_only_parent_commit": "ab30e0641cc9973c292b0d679800b4d9baf69cb1",
        "freeze_blob": FREEZE_BLOB, "R84_parent_SHA": PARENT,
        "seeds": list(SEEDS), "results": results,
        "status": g["classification_pass"] if pass_all else g["classification_fail"],
        "no_model_training": True, "CALIBRATION_first_use": True,
        "QUALIFICATION_DEV_OOD_generated": False,
        "scientific_learning_pass": False,
        "all_process_seconds": time.perf_counter() - begin,
        "platform": platform.platform()}
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("x", encoding="utf-8") as f:
        json.dump(receipt, f, indent=2, sort_keys=True, allow_nan=False)
        f.write("\n")
    return receipt


